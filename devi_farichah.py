# Reproject citra ke sistem koordinat UTM (citra Sentinel 2A 2020)
from rasterio.warp import calculate_default_transform, reproject, Resampling

def reproject_to_utm(src_path, dst_path, dst_crs="EPSG:32750"):
    with rasterio.open(src_path) as src:
        transform, w, h = calculate_default_transform(src.crs, dst_crs, src.width, src.height, *src.bounds)
        kwargs = src.meta.copy()
        kwargs.update(crs=dst_crs, transform=transform, width=w, height=h)

        with rasterio.open(dst_path, "w", **kwargs) as dst:
            for i in range(1, src.count + 1):
                reproject(
                    source=rasterio.band(src, i),
                    destination=rasterio.band(dst, i),
                    src_transform=src.transform, src_crs=src.crs,
                    dst_transform=transform, dst_crs=dst_crs,
                    resampling=Resampling.nearest)
    print(f"Selesai reproject: {dst_path}")

reproject_to_utm("Sarbagita_2020.tif", "Sarbagita_2020_utm.tif")

