# Menghitung persentase perubahan tiap kelas dari 2020 ke 2023
label_urut = sorted(DAFTAR_KELAS.keys())
n = len(label_urut)
matriks = np.zeros((n, n))

for i, kelas_awal in enumerate(label_urut):
    for j, kelas_akhir in enumerate(label_urut):
        matriks[i, j] = np.sum((peta_2020 == kelas_awal) & (peta_2023 == kelas_akhir))

total_per_baris = matriks.sum(axis=1, keepdims=True)
total_per_baris[total_per_baris == 0] = 1
matriks_prob = matriks / total_per_baris

print("Matriks probabilitas:")
print(pd.DataFrame(matriks_prob, index=DAFTAR_KELAS.values(), columns=DAFTAR_KELAS.values()))

# Menerapkan probabilitas untuk prediksi peta tutupan lahan 2026
np.random.seed(42)
peta_2026 = peta_2023.copy()

for i, kelas in enumerate(label_urut):
    lokasi = np.where(peta_2023 == kelas)
    jumlah_piksel = len(lokasi[0])
    if jumlah_piksel == 0:
        continue
    kelas_baru = np.random.choice(label_urut, size=jumlah_piksel, p=matriks_prob[i])
    peta_2026[lokasi] = kelas_baru

